export function rollRole(){
  const total = ROLES.reduce((s,r) => s + r.weight, 0);
  let x = Math.random() * total;
  for (const r of ROLES){ x -= r.weight; if (x <= 0) return r; }
  return ROLES[0];
}
export function roleById(id){ return ROLES.find(r => r.id === id); }
